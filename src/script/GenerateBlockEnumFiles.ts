import { writeFile } from 'fs/promises'
import { EELVL_BLOCKS } from '@/webtool/eelvl/block/EelvlBlocks.ts'
import { PWCatalog } from 'pw-js-api'
import { EER_BLOCKS } from '@/webtool/eer/block/EerBlocks.ts'

await generateBlockEnumFiles()

async function generateBlockEnumFiles() {
  await generatePwBlockNameEnum()
  await generateEelvlBlockIdEnum()
  await generateEerBlockIdEnum()
}

async function generatePwBlockNameEnum() {
  // Object.values protects against sparse arrays.
  const blocks = Object.values(await PWCatalog.getBlocks())
  const blocksSorted = blocks.sort((a, b) => a.id - b.id)

  let tsOutput = getGeneratedFileHeading()
  tsOutput += 'export enum PwBlockName {\n'

  for (let i = 0, len = blocksSorted.length; i < len; i++) {
    tsOutput += `  ${blocksSorted[i].paletteId.toUpperCase()} = '${blocksSorted[i].paletteId.toUpperCase()}',\n`
  }

  tsOutput += '}\n\nexport type PwBlockNameKeys = keyof typeof PwBlockName\n'

  await writeFile('./src/core/gen/PwBlockName.ts', tsOutput)
}

async function generateEelvlBlockIdEnum() {
  const blocks = EELVL_BLOCKS

  let tsOutput = getGeneratedFileHeading()
  tsOutput += 'export enum EelvlBlockId {\n'

  for (let i = 0, len = blocks.length; i < len; i++) {
    tsOutput += `  ${blocks[i].name} = ${blocks[i].id},\n`
  }

  tsOutput += '}\n\nexport type EelvlBlockIdKeys = keyof typeof EelvlBlockId\n'

  await writeFile('./src/webtool/eelvl/gen/EelvlBlockId.ts', tsOutput)
}

async function generateEerBlockIdEnum() {
  const blocks = EER_BLOCKS

  let tsOutput = getGeneratedFileHeading()
  tsOutput += 'export enum EerBlockId {\n'

  for (let i = 0, len = blocks.length; i < len; i++) {
    tsOutput += `  ${blocks[i].name} = ${blocks[i].id},\n`
  }

  tsOutput += '}\n\nexport type EerBlockIdKeys = keyof typeof EerBlockId\n'

  await writeFile('./src/webtool/eer/gen/EerBlockId.ts', tsOutput)
}

function getGeneratedFileHeading() {
  return '// DO NOT MODIFY THIS FILE BY HAND!\n' + '// This file is generated by GenerateBlockEnumFiles.ts\n'
}
