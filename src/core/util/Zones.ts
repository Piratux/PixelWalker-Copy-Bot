import { ProtoGen } from 'pw-js-api'
import { IZone, Zone, ZoneMembership } from 'pw-js-world'

export function createZone(overrides: Partial<IZone> = {}): Zone {
  const zone: IZone = {
    id: '',
    name: '',
    priority: 0,
    hue: 0,
    membershipRle: new ZoneMembership(0, 0),
    vision: ProtoGen.ZoneVision.INHERIT,
    visionCombine: ProtoGen.ZoneVision.INHERIT,
    visionOutside: ProtoGen.ZoneVision.INHERIT,
    hasVisionColor: false,
    visionColor: 0,
    cameraModeX: ProtoGen.ZoneCameraMode.INHERIT,
    cameraModeY: ProtoGen.ZoneCameraMode.INHERIT,
    cameraTarget: ProtoGen.ZoneCameraTarget.INHERIT,
    cameraMovement: ProtoGen.ZoneCameraMovement.INHERIT,
    cameraFollowMovement: ProtoGen.ZoneCameraMovement.INHERIT,
    lighting: ProtoGen.ZoneLighting.INHERIT,
    lightColor: 0xffffff,
    lightFeatherTop: 0,
    lightFeatherRight: 0,
    lightFeatherBottom: 0,
    lightFeatherLeft: 0,
    lightMarginTop: 0,
    lightMarginRight: 0,
    lightMarginBottom: 0,
    lightMarginLeft: 0,
    lightSmoothing: 0,
    playerLight: ProtoGen.ZonePlayerLight.INHERIT,
    playerLightRadius: 0,
    playerLightStrength: 0,
    playerLightColor: 0xffffff,
    fog: ProtoGen.ZoneFog.INHERIT,
    fogColor: 0xffffff,
    fogOpacity: 0,
    fogDensity: 0,
    fogDirection: 0,
    fogSpeed: 0,
    fogFeatherTop: 0,
    fogFeatherRight: 0,
    fogFeatherBottom: 0,
    fogFeatherLeft: 0,
    fogMarginTop: 0,
    fogMarginRight: 0,
    fogMarginBottom: 0,
    fogMarginLeft: 0,
    fogSmoothing: 0,
    distortion: ProtoGen.ZoneDistortion.INHERIT,
    distortionStrength: 0,
    distortionScale: 0,
    distortionSpeed: 0,
    distortionFeatherTop: 0,
    distortionFeatherRight: 0,
    distortionFeatherBottom: 0,
    distortionFeatherLeft: 0,
    distortionMarginTop: 0,
    distortionMarginRight: 0,
    distortionMarginBottom: 0,
    distortionMarginLeft: 0,
    distortionSmoothing: 0,
    ...overrides,
  }
  return new Zone(zone, zone.membershipRle._width, zone.membershipRle._height)
}
